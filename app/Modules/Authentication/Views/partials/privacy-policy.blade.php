    <h3>Introduction</h3>
    <p>The SK OnePortal System values your privacy and protects your personal information in accordance with Republic Act No. 10173 (Data Privacy Act of 2012).</p>

    <h3>Information Collected</h3>
    <p>The system may collect:</p>
    <p><strong>Personal Information</strong></p>
    <ul>
        <li>Full Name</li>
        <li>Date of Birth</li>
        <li>Age</li>
        <li>Sex</li>
        <li>Civil Status</li>
        <li>Address</li>
        <li>Barangay</li>
        <li>Contact Number</li>
        <li>Email Address</li>
        <li>Educational Background</li>
        <li>Employment Status</li>
        <li>Voter Information (if applicable)</li>
        <li>E-signature</li>
        <li>Valid ID (optional)</li>
        <li>Barangay Clearance (optional)</li>
        <li>Other information required under the KK Profiling Form</li>
    </ul>
    <p><strong>Account Information</strong></p>
    <ul>
        <li>Encrypted Password</li>
    </ul>
    <p><strong>System Information</strong></p>
    <ul>
        <li>Audit logs</li>
        <li>Submitted forms</li>
    </ul>

    <h3>Purpose of Collection</h3>
    <p>Your information is collected for:</p>
    <ul>
        <li>KK Profiling</li>
        <li>Youth development planning</li>
        <li>Government statistical reports</li>
        <li>Program implementation</li>
        <li>Scholarship and assistance programs</li>
        <li>Community activities</li>
        <li>Updating official youth records</li>
    </ul>

    <h3>Protection of Information</h3>
    <p>The system safeguards your information through:</p>
    <ul>
        <li>Password encryption</li>
        <li>Secure signin authentication</li>
        <li>Authorized access only</li>
        <li>Database protection</li>
        <li>Audit logs</li>
    </ul>

    <h3>Data Sharing</h3>
    <p>Your information may only be accessed by:</p>
    <ul>
        <li>Authorized SK Officials</li>
        <li>SK Federation</li>
        <li>Authorized Municipal Government Offices</li>
        <li>Government agencies when required by law</li>
    </ul>
    <p>Personal information will not be sold or used for commercial purposes.</p>

    <h3>Data Retention</h3>
    <p>Your information will be retained only for as long as necessary for official government purposes or as required by law.</p>

    <h3>Your Rights</h3>
    <p>Under the Data Privacy Act of 2012, you have the right to:</p>
    <ul>
        <li>Be informed about the collection and processing of your personal information.</li>
        <li>Access your personal data.</li>
        <li>Request correction of inaccurate or incomplete information.</li>
        <li>Request deletion of personal data when legally applicable.</li>
        <li>Withdraw consent, subject to legal or regulatory requirements.</li>
        <li>File a complaint with the National Privacy Commission if you believe your privacy rights have been violated.</li>
    </ul>
